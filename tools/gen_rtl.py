"""Generate the RTL's constant tables from the model (M7, M8).

rtl/fft256/fft256_twiddle.v: round(65536 e^{-2 pi i j / 256}), j < 128,
the same values as fx.Fft.init and twin.twiddles, as an 18-bit ROM.
rtl/chan_emu/chan_emu_rtab.v: the emulator's noise radius table
(harness/chanemu.radius_table).
Run:  .venv/bin/python -I tools/gen_rtl.py   (the output is committed)
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from harness import twin                                     # noqa: E402

N = 256


def twiddle_rom() -> str:
    tw = twin.twiddles(N)
    lines = [
        "// Generated by tools/gen_rtl.py from harness/twin.py: do not edit.",
        f"// round(65536 e^(-2 pi i j / {N})), j < {N // 2}, 18-bit two's complement (1.0 is exact).",
        "module fft256_twiddle (",
        "    input  wire        [6:0]  j,",
        "    output reg  signed [17:0] wr,",
        "    output reg  signed [17:0] wi",
        ");",
        "    always @(*) begin",
        "        case (j)",
    ]
    for j, (re, im) in enumerate(tw):
        lines.append(f"            7'd{j}: begin wr = {fmt(re)}; wi = {fmt(im)}; end")
    lines += ["            default: begin wr = 18'sd0; wi = 18'sd0; end",
              "        endcase", "    end", "endmodule", ""]
    return "\n".join(lines)


def fmt(v: int) -> str:
    return f"-18'sd{-v}" if v < 0 else f"18'sd{v}"


def radius_rom() -> str:
    from harness import chanemu
    tab = chanemu.radius_table()
    lines = [
        "// Generated by tools/gen_rtl.py from harness/chanemu.py: do not edit.",
        "// round(2^11 sqrt(E[-2 ln u])) over the bins of u: {min(clz u, 23), 8 bits after the leading one}.",
        "// Registered output (one block RAM).",
        "module chan_emu_rtab (",
        "    input  wire        clk,",
        "    input  wire [12:0] addr,",
        "    output reg  [13:0] r",
        ");",
        "    always @(posedge clk) begin",
        "        case (addr)",
    ]
    for a, v in enumerate(tab):
        lines.append(f"            13'd{a}: r <= 14'd{v};")
    lines += ["            default: r <= 14'd0;", "        endcase", "    end", "endmodule", ""]
    return "\n".join(lines)


TABLES = {"rtl/fft256/fft256_twiddle.v": twiddle_rom, "rtl/chan_emu/chan_emu_rtab.v": radius_rom}


def main():
    for path, gen in TABLES.items():
        out = ROOT / path
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(gen())
        print(out.relative_to(ROOT))


if __name__ == "__main__":
    main()
